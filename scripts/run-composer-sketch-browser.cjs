const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { launchOptions, requireTooling } = require('./lib/browser.cjs');
const { expectScreenshot } = require('./lib/visual.cjs');

/**
 * The Sketch captures follow drag gestures whose pointer coordinates are derived from live
 * boundingBox() calls, so the drawn geometry carries a little platform-dependent jitter that
 * cannot be removed without rewriting the gesture into fixed coordinates. Measured spread is
 * ~1.7%, so these two use a wider band; everything else keeps the tight default.
 */
const SKETCH_TOLERANCE = 0.03;
const { chromium } = requireTooling('Composer sketch browser');
(async () => {
 const browser = await chromium.launch(launchOptions());
 try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.resolve('tmp/composer-browser/index.html')).href);
  await page.waitForFunction(() => window.ready);
  const state = () => page.evaluate(() => window.composerTest.view.history.draft);
  await page.getByRole('button', { name: 'Switch Composer mode' }).click();
  assert.equal((await state()).mode, 'sketch');
  await page.locator('.cmm-composer-stage > svg').dblclick({ position: { x: 180, y: 180 } });
  await page.locator('.test-modal input').fill('Loose thought');
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  assert.equal((await state()).sketch.notes[0].title, 'Loose thought');
  const body = page.locator('.cmm-composer-body textarea');
  await body.fill('A separate Markdown body');
  assert.equal((await state()).sketch.notes[0].body, 'A separate Markdown body');
  const note = page.locator('[data-free-note-id]').first();
  const startX = (await state()).sketch.notes[0].position.x;
  const box = await note.boundingBox();
  await page.mouse.move(box.x + 40, box.y + 30); await page.mouse.down();
  await page.mouse.move(box.x + 130, box.y + 75, { steps: 4 }); await page.mouse.up();
  let draft = await state(); assert.ok(draft.sketch.notes[0].position.x > startX + 50);
  const noteId = draft.sketch.notes[0].id, rootId = draft.root.id;
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.locator(`[data-node-id="${rootId}"] [role="link"]`).click();
  await page.locator(`[data-free-note-id="${noteId}"]`).click();
  draft = await state(); assert.equal(draft.sketch.links.length, 1);
  const linkPath = page.locator(`[data-link-id="${draft.sketch.links[0].id}"]`);
  const pathBeforeMove = await linkPath.getAttribute('d');
  const linkedBox = await page.locator(`[data-free-note-id="${noteId}"]`).boundingBox();
  await page.mouse.move(linkedBox.x + 30, linkedBox.y + 24); await page.mouse.down();
  await page.mouse.move(linkedBox.x + 75, linkedBox.y + 60, { steps: 4 }); await page.mouse.up();
  assert.notEqual(await linkPath.getAttribute('d'), pathBeforeMove, 'association follows note movement');
  await page.getByRole('button', { name: 'Arrow', exact: true }).click();
  const canvas = page.locator('.cmm-composer-stage > svg'), rect = await canvas.boundingBox();
  await page.mouse.move(rect.x + 100, rect.y + 350); await page.mouse.down(); await page.mouse.move(rect.x + 200, rect.y + 380); await page.mouse.up();
  assert.equal((await state()).sketch.annotations.length, 1);
  assert.equal(await page.getByRole('button', { name: 'Select', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.mouse.move(4, 4);await page.waitForTimeout(60);
  const sketchShot = await page.screenshot({ path: 'tmp/composer-browser/sketch.png' });
  expectScreenshot('composer-sketch', sketchShot, { maxDiff: SKETCH_TOLERANCE });
  await page.evaluate(() => {
    // The Sketch surface derives from the theme, so dark mode means dark theme variables.
    document.body.classList.add('theme-dark');
    document.body.style.setProperty('--background-primary', '#1e1e1e');
    document.body.style.setProperty('--background-primary-alt', '#262626');
    document.body.style.setProperty('--text-normal', '#dadada');
  });
  await page.setViewportSize({ width: 800, height: 700 });
  assert.equal(await page.locator('.cmm-composer-sketch-tools').isVisible(), true);
  // The stage must follow the theme instead of staying a hardcoded light paper.
  assert.equal(await page.locator('.cmm-composer-stage').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(30, 30, 30)');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    document.body.classList.remove('theme-dark');
    document.body.style.removeProperty('--background-primary');
    document.body.style.removeProperty('--background-primary-alt');
    document.body.style.removeProperty('--text-normal');
  });
  await page.waitForTimeout(650);
  const id = (await state()).draftId;
  await page.evaluate(async id => { const view = window.composerTest.view; await view.setState({ draftId: id }, { history: false }); }, id);
  draft = await state(); assert.equal(draft.sketch.notes[0].body, 'A separate Markdown body'); assert.equal(draft.sketch.links.length, 1);
  await page.getByRole('button', { name: 'Switch Composer mode' }).click();
  assert.equal((await state()).mode, 'structured');
  await page.getByRole('button', { name: 'Switch Composer mode' }).click();
  assert.equal(await page.locator('[data-free-note-id]').count(), 1);
  await page.getByRole('button', { name: 'Ideas', exact: true }).click();
  const capture = page.getByRole('textbox', { name: 'Capture an idea…', exact: true });
  await capture.fill('Inbox seed'); await capture.press('Enter');
  const sourceId = (await state()).unsorted[0].id;
  await page.locator(`.cmm-composer-unsorted-node[data-node-id="${sourceId}"]`).dragTo(page.locator('.cmm-composer-stage > svg'), { targetPosition: { x: 100, y: 350 } });
  draft = await state(); assert.equal(draft.unsorted[0].title, 'Inbox seed');
  assert.equal(draft.sketch.notes.find(n => n.sourceIdeaId === sourceId).title, 'Inbox seed');
  await page.getByRole('button', { name: 'Arrange layout' }).click();
  assert.deepEqual((await state()).sketch.positions, {});
  await page.locator(`[data-free-note-id="${noteId}"]`).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Convert to heading' }).click();
  draft = await state(); assert.equal(draft.sketch.notes.length, 1); assert.equal(draft.root.children[0].title, 'Loose thought');
  assert.equal(draft.root.children[0].body, 'A separate Markdown body');
  assert.deepEqual(errors, []);
  const regression = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await regression.goto(pathToFileURL(path.resolve('tmp/composer-browser/index.html')).href);
  await regression.waitForFunction(() => window.ready);
  await regression.getByRole('button', { name: 'Switch Composer mode' }).click();
  const regressionCanvas = regression.locator('.cmm-composer-stage > svg');
  const stageBefore = await regressionCanvas.boundingBox();
  assert.equal(await regression.locator('.cmm-composer-split').evaluate(el => el.classList.contains('has-body')), true);
  await regressionCanvas.dblclick({ position: { x: stageBefore.width - 110, y: 170 } });
  await regression.locator('.test-modal input').fill('Right edge note');
  await regression.getByRole('button', { name: 'Confirm', exact: true }).click();
  const stageAfter = await regressionCanvas.boundingBox();
  const edgeNote = regression.locator('[data-free-note-id]').first();
  let edgeBox = await edgeNote.boundingBox();
  assert.equal(stageAfter.width, stageBefore.width, 'selecting a note must not resize the Sketch canvas');
  assert.ok(edgeBox.x + edgeBox.width <= stageAfter.x + stageAfter.width + 4,
    `new note must remain visible: ${JSON.stringify({ edgeBox, stageAfter })}`);
  const edgeId = await edgeNote.getAttribute('data-free-note-id');
  const xBefore = await regression.evaluate(id => window.composerTest.view.draft.sketch.notes.find(n => n.id === id).position.x, edgeId);
  await regression.mouse.move(edgeBox.x + 30, edgeBox.y + 25);
  await regression.mouse.down(); await regression.mouse.move(edgeBox.x - 90, edgeBox.y + 55, { steps: 5 }); await regression.mouse.up();
  const xAfter = await regression.evaluate(id => window.composerTest.view.draft.sketch.notes.find(n => n.id === id).position.x, edgeId);
  assert.ok(xAfter < xBefore - 50, 'right-side note can be dragged');
  await regression.locator(`[data-free-note-id="${edgeId}"]`).dblclick({ position: { x: 30, y: 25 } });
  assert.equal(await regression.locator('.test-modal').isVisible(), true, 'double-click opens note rename');
  await regression.locator('.test-modal input').fill('Renamed note');
  await regression.getByRole('button', { name: 'Confirm', exact: true }).click();
  assert.equal(await regression.evaluate(id => window.composerTest.view.draft.sketch.notes.find(n => n.id === id).title, edgeId), 'Renamed note');
  await regression.getByRole('button', { name: 'Arrow', exact: true }).click();
  await regression.keyboard.press('Escape');
  assert.equal(await regression.getByRole('button', { name: 'Select', exact: true }).getAttribute('aria-pressed'), 'true');
  await regression.getByRole('button', { name: 'Text note', exact: true }).click();
  const markCanvas = await regressionCanvas.boundingBox();
  await regression.mouse.click(markCanvas.x + 105, markCanvas.y + 300);
  await regression.locator('.test-modal input').fill('Review this');
  await regression.getByRole('button', { name: 'Confirm', exact: true }).click();
  const textMark = regression.locator('.cmm-sketch-annotation.is-text').first();
  await textMark.dblclick();
  assert.equal(await regression.locator('.test-modal').isVisible(), true, 'double-click opens text annotation edit');
  await regression.locator('.test-modal input').fill('Revised');
  await regression.getByRole('button', { name: 'Confirm', exact: true }).click();
  assert.equal(await regression.evaluate(() => window.composerTest.view.draft.sketch.annotations[0].text), 'Revised');
  const regressionRoot = await regression.evaluate(() => window.composerTest.view.draft.root.id);
  const rootShape = regression.locator(`[data-node-id="${regressionRoot}"] [role="link"]`);
  const rootClickBox = await rootShape.boundingBox();
  const rootClick = { x: rootClickBox.width - 18, y: rootClickBox.height / 2 };
  await regression.getByRole('button', { name: 'Circle', exact: true }).click();
  await rootShape.click({ position: rootClick });
  let anchored = await regression.evaluate(id => window.composerTest.view.draft.sketch.annotations.filter(a => a.anchorId === id), regressionRoot);
  assert.equal(anchored.length, 1, 'circle click attaches a mark to the heading');
  assert.equal(anchored[0].kind, 'ellipse');
  await regression.getByRole('button', { name: 'Highlight', exact: true }).click();
  await rootShape.click({ position: rootClick });
  anchored = await regression.evaluate(id => window.composerTest.view.draft.sketch.annotations.filter(a => a.anchorId === id), regressionRoot);
  assert.equal(anchored.length, 2, 'highlight click attaches a mark to the heading');
  const highlightId = anchored.find(a => a.kind === 'highlight').id;
  assert.equal(await regression.locator(`[data-node-id="${regressionRoot}"] [data-annotation-id="${highlightId}"]`).count(), 1);
  const rootBefore = await rootShape.boundingBox();
  await regression.mouse.move(rootBefore.x + rootBefore.width - 30, rootBefore.y + rootBefore.height / 2);
  await regression.mouse.down(); await regression.mouse.move(rootBefore.x + rootBefore.width + 18, rootBefore.y + rootBefore.height / 2 + 30, { steps: 5 }); await regression.mouse.up();
  const rootAfter = await rootShape.boundingBox();
  assert.ok(rootAfter.x > rootBefore.x + 30, 'heading and its attached marks move together');
  await regression.getByRole('button', { name: 'Circle', exact: true }).click();
  const drawStart = { x: markCanvas.x + 200, y: markCanvas.y + 330 };
  await regression.mouse.move(drawStart.x, drawStart.y); await regression.mouse.down();
  await regression.mouse.move(drawStart.x + 70, drawStart.y + 35, { steps: 3 });
  assert.equal(await regression.locator('.cmm-sketch-preview').count(), 1, 'draw tool gives live preview');
  await regression.mouse.up();
  assert.equal(await regression.locator('.cmm-sketch-preview').count(), 0);
  assert.equal(await regression.evaluate(() => window.composerTest.view.draft.sketch.annotations.filter(a => a.kind === 'ellipse').length), 2);
  const looseCircle = regression.locator('.cmm-sketch-annotation.is-ellipse:not([data-anchored])').last();
  const circleBox = await looseCircle.boundingBox();
  await regression.mouse.click(circleBox.x + circleBox.width / 2, circleBox.y + 2);
  assert.equal(await regression.locator('.cmm-sketch-handle').count(), 2, 'selected mark exposes editable ends');
  const selectedCircleId = await looseCircle.getAttribute('data-annotation-id');
  const oldEnd = await regression.evaluate(id => window.composerTest.view.draft.sketch.annotations.find(a => a.id === id).end.x, selectedCircleId);
  const endHandle = regression.locator(`[data-annotation-id="${selectedCircleId}"] [data-endpoint="end"]`);
  const handleBox = await endHandle.boundingBox();
  await regression.mouse.move(handleBox.x + handleBox.width / 2, handleBox.y + handleBox.height / 2);
  await regression.mouse.down(); await regression.mouse.move(handleBox.x + handleBox.width / 2 + 32, handleBox.y + handleBox.height / 2 + 8, { steps: 4 }); await regression.mouse.up();
  assert.ok(await regression.evaluate(id => window.composerTest.view.draft.sketch.annotations.find(a => a.id === id).end.x, selectedCircleId) > oldEnd + 20, 'dragging a handle resizes the mark');
  await regression.screenshot({ path: 'tmp/composer-browser/sketch-annotations.png' });
  expectScreenshot('composer-sketch-annotations', await regression.screenshot(), { maxDiff: SKETCH_TOLERANCE });
  await regression.waitForTimeout(650);
  const persistedId = await regression.evaluate(() => window.composerTest.view.draft.draftId);
  await regression.evaluate(async id => { await window.composerTest.view.setState({ draftId: id }, { history: false }); }, persistedId);
  assert.equal(await regression.evaluate(id => window.composerTest.view.draft.sketch.annotations.filter(a => a.anchorId === id).length, regressionRoot), 2, 'attached marks survive reopening');
  await regression.getByRole('button', { name: 'Switch Composer mode' }).click();
  assert.equal(await regression.locator('.cmm-sketch-overlays').count(), 0, 'Structured must clear free objects');
  assert.equal(await regression.evaluate(() => window.composerTest.view.selectedNote), undefined);
  assert.ok(!(await regression.locator('.cmm-composer-breadcrumb').textContent()).includes('Free note'));
  await regression.close();
  console.log('PASS Composer Sketch browser: mode switching, note creation/edit/drag, link, annotation, save/reopen, conversion');
 } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
