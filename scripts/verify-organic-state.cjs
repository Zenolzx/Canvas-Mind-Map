const assert = require('node:assert/strict');
const esbuild = require('esbuild');
function load(path) {
    const out = esbuild.buildSync({ entryPoints: [path], bundle: true, platform: 'node', format: 'cjs', write: false });
    const m = { exports: {} }; new Function('module', 'exports', out.outputFiles[0].text)(m, m.exports); return m.exports;
}
const { PluginDataStore } = load('src/PluginDataStore.ts');
const { OrganicStateStore } = load('src/organic/OrganicStateStore.ts');
const { OrganicViewportController } = load('src/organic/OrganicViewportController.ts');
const { sourceFingerprint } = load('src/organic/OrganicViewState.ts');
const { reconcileOrganicModel } = load('src/organic/OrganicNodeIdentity.ts');
const { buildMindMapModel } = load('src/core/MindMapModel.ts');
const { OrganicAutoRefreshController } = load('src/organic/OrganicAutoRefreshController.ts');
const { OrganicViewState } = load('src/organic/OrganicViewState.ts');
const { OrganicInteractionController } = load('src/organic/OrganicInteractionController.ts');
(async () => {
    const saved = { readerVisible: true, splitRatio: .67, fingerprint: sourceFingerprint('# A'), collapsed: ['heading:/A:1'],
        viewport: { zoom: 2, center: { x: 100, y: -30 } }, focusNode: null,
        reading: { rootNode: null, currentNode: null }, selectedNode: null, layout: 'organic-radial' };
    let enabled = true, writes = [], settings = { language: 'auto' }, release;
    const writer = new PluginDataStore(() => ({ ...settings, organicState: store.data }), async data => {
        if (release === undefined) await new Promise(resolve => { release = resolve; }); writes.push(data);
    });
    const store = new OrganicStateStore({}, () => writer.save(), () => enabled);
    store.put('a.md', saved);
    const first = store.flush(); await new Promise(resolve => setTimeout(resolve, 0));
    settings.language = 'en'; store.put('a.md', { ...saved, collapsed: [] });
    const second = store.flush(); release(); await Promise.all([first, second]);
    assert.equal(writes.length, 2); assert.equal(writes[1].language, 'en');
    assert.deepEqual(writes[1].organicState.files['a.md'].collapsed, []);
    await store.flush(); assert.equal(writes.length, 2, 'closing idle tab must not overwrite newer state');
    const reopened = new OrganicStateStore(writes[1].organicState, async () => {}, () => enabled);
    assert.deepEqual(reopened.get('a.md').viewport, saved.viewport);
    assert.equal(reopened.get('a.md').readerVisible, true);
    assert.equal(reopened.get('a.md').splitRatio, .67);
    reopened.rename('a.md', 'folder/a.md'); assert.equal(reopened.get('a.md'), undefined);
    assert.ok(reopened.get('folder/a.md')); reopened.remove('folder/a.md'); await reopened.flush();
    assert.equal(reopened.get('folder/a.md'), undefined);
    enabled = false; store.put('disabled.md', saved); assert.equal(store.get('a.md'), undefined);
    assert.equal(store.data.files['disabled.md'], undefined); enabled = true;
    await store.reset(); assert.equal(store.get('a.md'), undefined);
    const ownerA = {}, ownerB = {};
    store.put('folder/note.md', saved, ownerA);
    store.put('folder/note.md', { ...saved, collapsed: [] }, ownerB);
    store.sync('folder/note.md', saved, ownerA);
    assert.deepEqual(store.get('folder/note.md').collapsed, [], 'background refresh cannot steal persistence ownership');
    store.rename('folder', 'moved'); assert.ok(store.get('moved/note.md'));
    store.remove('moved'); await store.flush(); assert.equal(store.get('moved/note.md'), undefined);
    assert.equal(new OrganicStateStore({ version: 99, files: { a: saved } }, async () => {}, () => true).get('a'), undefined);
    assert.equal(new OrganicStateStore({ version: 1, files: { a: { ...saved, viewport: { zoom: NaN } } } }, async () => {}, () => true).get('a'), undefined);
    const viewport = new OrganicViewportController(); viewport.scale = 2;
    viewport.center(saved.viewport.center, 1000, 700);
    assert.deepEqual(viewport.snapshot(1000, 700), saved.viewport);
    viewport.center(saved.viewport.center, 500, 300);
    assert.deepEqual(viewport.snapshot(500, 300), saved.viewport);
    let callback, painted;
    const win = { performance: { now: () => 0 }, requestAnimationFrame: cb => { callback = cb; return 1; }, cancelAnimationFrame: () => { callback = undefined; } };
    viewport.follow({ x: 500, y: 300 }, 800, 600, win, 100, offset => { painted = { ...offset }; });
    callback(40);
    assert.deepEqual(viewport.offset, painted, 'animation frame must update canonical viewport');
    viewport.pan(31, -17);
    assert.deepEqual(viewport.offset, { x: painted.x + 31, y: painted.y - 17 });
    const interrupted = { ...viewport.offset }; viewport.cancel();
    assert.deepEqual(viewport.offset, interrupted, 'cancel must not snap to old animation target');
    assert.equal(callback, undefined);
    const parse = text => buildMindMapModel(text, { title: 'note' });
    const old = reconcileOrganicModel(parse('# Root\n## A\nunique body\n## Repeat\n## Repeat'));
    const renamed = reconcileOrganicModel(parse('# Root\n## Renamed\nunique body\n## Repeat\n## Repeat'), old.identities);
    assert.equal(renamed.model.nodes[1].id, old.model.nodes[1].id, 'unique preserved body matches rename');
    assert.notEqual(renamed.model.nodes[2].id, old.model.nodes[2].id, 'ambiguous duplicates must not inherit state');
    const shifted = reconcileOrganicModel(parse('\n# Root\n## A\nunique body\n## Repeat\n## Repeat'), old.identities);
    assert.deepEqual(shifted.model.nodes.map(n => n.id), old.model.nodes.map(n => n.id));
    const beforeParentRename = reconcileOrganicModel(parse('# Root\n## Parent\nunique parent body\n### Child\n#### Grandchild'));
    const afterParentRename = reconcileOrganicModel(parse('# Root\n## Renamed\nunique parent body\n### Child\n#### Grandchild'), beforeParentRename.identities);
    assert.deepEqual(afterParentRename.model.nodes.map(n => n.id), beforeParentRename.model.nodes.map(n => n.id), 'matched parents anchor descendants');
    let refreshes = 0, invalidations = 0;
    const auto = new OrganicAutoRefreshController(async () => { refreshes++; }, () => true, () => { invalidations++; }, 5);
    for (let i = 0; i < 20; i++) auto.changed();
    await new Promise(resolve => setTimeout(resolve, 20));
    assert.equal(refreshes, 1); assert.equal(invalidations, 20);
    auto.changed(); auto.close(); await new Promise(resolve => setTimeout(resolve, 10)); assert.equal(refreshes, 1);
    const model = parse('# Root\n## A\n### Hidden\n#### streamAssistantResponse\n## B\n### Other');
    const state = new OrganicViewState(); state.reset(model, 'organic-radial');
    const interaction = new OrganicInteractionController(state); interaction.update(model);
    const node = title => model.nodes.find(n => n.title === title).id;
    interaction.focus(node('B'));
    assert.ok(!interaction.projection().model.nodes.some(n => n.title === 'A'));
    interaction.search.update(model, 'STREAMassistant');
    assert.equal(interaction.search.results.length, 1); assert.ok(interaction.focusPaused);
    assert.ok(!interaction.projection().collapsed.has(node('Hidden')));
    assert.ok(state.collapsed.has(node('Hidden')), 'search must not change durable collapse');
    interaction.clearSearch(); assert.ok(!interaction.focusPaused); assert.equal(state.focusNode, node('B'));
    interaction.focus(null); interaction.read(node('A'));
    assert.equal(interaction.readingStep(1), node('Hidden'));
    assert.equal(interaction.readingStep(1), node('streamAssistantResponse'));
    assert.ok(!interaction.projection().collapsed.has(node('Hidden')));
    interaction.read(null); assert.ok(interaction.projection().collapsed.has(node('Hidden')));
    interaction.read(node('A')); interaction.readingStep(1); interaction.readingStep(1);
    interaction.toggle(node('Hidden')); assert.equal(state.reading.currentNode, node('Hidden'));
    assert.ok(interaction.projection().collapsed.has(node('Hidden')), 'manual collapse takes precedence over reading reveal');
    assert.equal(model.nodes.length, 6, 'projection must not mutate source model');
    console.log('PASS: serialized settings/state writes, reopening, last interaction wins, rename/delete/reset, disabled/bad state, Reader width/visibility, canonical animation frames and interrupted pan.');
})().catch(error => { console.error(error); process.exitCode = 1; });
